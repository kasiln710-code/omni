// active lang
let currentLang = 'zh';
let currentPricing = 'm';

function switchLang(lang) {
  currentLang = lang;
  const data = I18N[lang];
  const isRTL = lang === 'ar';
  document.documentElement.setAttribute('lang', lang === 'zh' ? 'zh-CN' : lang === 'ar' ? 'ar' : 'en');
  document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');

  // update flag + label
  const flags = { zh: '🇨🇳', en: '🇺🇸', ar: '🇸🇦' };
  const labels = { zh: '中文', en: 'EN', ar: 'عربية' };
  document.getElementById('langFlag').textContent = flags[lang];
  document.getElementById('langLabel').textContent = labels[lang];

  // mark active option
  document.querySelectorAll('.lang-option').forEach(el => el.classList.remove('active'));
  const idx = { zh: 0, en: 1, ar: 2 };
  const opts = document.querySelectorAll('.lang-option');
  if (opts[idx[lang]]) opts[idx[lang]].classList.add('active');

  // apply translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (data[key] !== undefined) el.textContent = data[key];
  });

  // price unit
  document.querySelectorAll('[data-i18n="pricing.per"]').forEach(el => {
    el.textContent = data["pricing.per"];
  });
}
